package forge.gamesimulationservice.model;

public class Draw {
    private int rank;
    private String card;

    public Draw() {
    }

    public int getRank() {
        return rank;
    }

    public void setRank(int rank) {
        this.rank = rank;
    }

    public String getCard() {
        return card;
    }

    public void setCard(String card) {
        this.card = card;
    }
}
