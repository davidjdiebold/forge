package forge.gamesimulationservice.model;

public class CardCount {
    private String card;
    private Integer count;

    public CardCount() {
    }

    public String getCard() {
        return card;
    }

    public void setCard(String card) {
        this.card = card;
    }

    public Integer getCount() {
        return count;
    }

    public void setCount(Integer count) {
        this.count = count;
    }
}
